def obter_ruas_bairro(nome_bairro: str) -> List[str]:
    """Retorna a lista de ruas reais cadastradas para o bairro."""
    perfil = obter_perfil_bairro(nome_bairro)
    return perfil.get('ruas', ['Avenida Principal', 'Rua Central'])


